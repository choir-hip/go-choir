package trustharness

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"
)

// Render returns the report's JSON and markdown bytes. Both are a pure
// function of the report (map keys are sorted by encoding/json and here).
func Render(rep Report) (jsonBytes, md []byte, err error) {
	jsonBytes, err = json.MarshalIndent(rep, "", "  ")
	if err != nil {
		return nil, nil, err
	}
	jsonBytes = append(jsonBytes, '\n')
	return jsonBytes, []byte(markdown(rep)), nil
}

func sortedKeys[V any](m map[string]V) []string {
	ks := make([]string, 0, len(m))
	for k := range m {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	return ks
}

func g(v float64) string { return fmt.Sprintf("%g", v) }

func optF(p *float64) string {
	if p == nil {
		return ""
	}
	return g(*p)
}

func markdown(r Report) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("# Trust evidence harness (MA7.9): %s\n\n", r.ComputerID)
	w("As of %s; build %s; inputs sha256 %s; deadline %s. Generated by cmd/trustharness from the stored inputs beside this file; ", r.AsOf.Format("2006-01-02T15:04:05Z"), r.BuildCommit, r.InputsSHA256, r.Deadline)
	w("rerun with `go run ./cmd/trustharness -from <dir> -check` to reproduce these bytes.\n\n")

	w("## (0') Inert rates per desk, model and prompt version\n\n")
	w("%s\n\n", r.Inert.Note)
	if len(r.Inert.Rows) > 0 {
		w("| desk | model | prompt | precommitments | inert | rate | delegations | inert | rate |\n|---|---|---|---|---|---|---|---|---|\n")
		for _, x := range r.Inert.Rows {
			w("| %s | %s | %s | %d | %d | %s | %d | %d | %s |\n", x.Desk, dash(x.Model), dash(x.PromptVersion), x.Precommitments, x.InertPrecommitments, g(x.InertPrecommitRate), x.Delegations, x.InertDelegations, g(x.InertDelegateRate))
		}
		w("| all | | | %d | %d | %s | %d | %d | %s |\n\n", r.Inert.Precommitments, r.Inert.InertPrecommitments, g(r.Inert.InertPrecommitRate), r.Inert.Delegations, r.Inert.InertDelegations, g(r.Inert.InertDelegateRate))
	}
	w("Judge agreement with the rules: %d sampled, %d agree.\n\n", r.Inert.Agreement.Sampled, r.Inert.Agreement.Agree)

	l := r.Ledger
	w("## (0) The mission's own precommitment ledger\n\n")
	w("`%s` (sha256 %s): %d records; resolutions %s; settled by %s.\n\n", l.Path, l.SHA256, l.Records, counts(l.ByResolution), counts(l.BySettler))
	p, iv := l.Probability, l.Interval
	w("| scores | n | value |\n|---|---|---|\n")
	w("| probability: Brier | %d | %s |\n| probability: log score | %d | %s |\n| probability: Brier skill vs 0.5 | %d | %s |\n| probability: sharpness, mean abs(p - 0.5) | %d | %s |\n", p.N, g(p.Brier), p.N, g(p.LogScore), p.N, g(p.BrierSkillVsHalf), p.N, g(p.Sharpness))
	w("| 80%% intervals: coverage | %d | %s (%d covered) |\n| 80%% intervals: mean interval score / estimate | %d | %s |\n| 80%% intervals: mean relative width | %d | %s |\n| point estimates: mean ln(observed/estimate) | %d | %s (mean abs %s) |\n\n", iv.N, g(iv.Coverage), iv.Covered, iv.N, g(iv.MeanScaledIntervalScore), iv.N, g(iv.MeanRelativeWidth), iv.NLogRatio, g(iv.MeanLogRatio), g(iv.MeanAbsLogRatio))
	w("Calibration of the probabilities:\n\n| bin | n | mean p | observed |\n|---|---|---|---|\n")
	for _, c := range p.Calibration {
		w("| [%s, %s) | %d | %s | %s |\n", g(c.Lo), g(c.Hi), c.N, g(c.MeanP), g(c.Freq))
	}
	w("\n| record | kind | resolution | settler | p | outcome | Brier | estimate | interval | observed | interval score |\n|---|---|---|---|---|---|---|---|---|---|---|\n")
	for _, x := range l.Scored {
		ivs := ""
		if x.Lo != nil {
			ivs = fmt.Sprintf("[%s, %s]", g(*x.Lo), g(*x.Hi))
		}
		w("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n", x.ID, x.Kind, x.Resolution, dash(x.Settler), optF(x.P), optF(x.Outcome), optF(x.Brier), optF(x.Estimate), ivs, optF(x.Observed), optF(x.IntervalScore))
	}
	for _, pr := range l.Problems {
		w("\nProblem: %s", pr)
	}
	w("\n\n## Pre-registered tests\n\n| test | status | n | reason |\n|---|---|---|---|\n")
	for _, t := range r.Tests {
		var ns []string
		for _, k := range sortedKeys(t.N) {
			ns = append(ns, fmt.Sprintf("%s %d", k, t.N[k]))
		}
		w("| %s %s | %s | %s | %s |\n", t.ID, t.Name, t.Status, strings.Join(ns, ", "), t.Reason)
	}
	for _, t := range r.Tests {
		if len(t.Metrics) == 0 {
			continue
		}
		w("\n%s metrics:", t.ID)
		for _, k := range sortedKeys(t.Metrics) {
			w(" %s %s;", k, g(t.Metrics[k]))
		}
		for _, bl := range t.Baselines {
			switch {
			case !bl.Available:
				w(" baseline %s unavailable (%s);", bl.Name, bl.Note)
			case bl.Degenerate:
				w(" baseline %s degenerate;", bl.Name)
			default:
				w(" baseline %s AUC %s;", bl.Name, g(bl.AUC))
			}
		}
		w("\n")
	}
	gt := r.GateTaps
	w("\n## (a) Owner taps the gate would have asked for\n\n")
	w("Material acts %d, gated %d (breaker %d); taps per day mean %s, median %s, p90 %s over %d days. %s\n", gt.Acts, gt.Gated, gt.Breaker, g(gt.TapsPerDayMean), g(gt.TapsPerDayMedian), g(gt.TapsPerDayP90), gt.DaysCounted, gt.Note)
	m := r.Measured
	w("\n## (c) Measured outcomes\n\n")
	w("Leases: %d (durable %d, renewals %d, revoked by a fidelity event %d); ended %d, duration hours median %s, p90 %s.", m.Leases.N, m.Leases.Durable, m.Leases.Renewals, m.Leases.RevokedByFidelity, m.Leases.NEnded, g(m.Leases.DurationHoursMedian), g(m.Leases.DurationHoursP90))
	for _, k := range sortedKeys(m.Leases.ByEndReason) {
		w(" %q %d;", k, m.Leases.ByEndReason[k])
	}
	if m.GatedActs.Served {
		w("\n\nGated acts on the tape: %d (approved %d, denied %d, open %d, breaker %d); minutes to the owner's answer median %s, p90 %s.", m.GatedActs.N, m.GatedActs.Approved, m.GatedActs.Denied, m.GatedActs.Open, m.GatedActs.Breaker, g(m.GatedActs.AnswerMinutesMedian), g(m.GatedActs.AnswerMinutesP90))
	} else {
		w("\n\nGated acts on the tape: the computer's build did not serve them.")
	}
	w(" Act gate counters since boot:")
	if len(m.ActGate) == 0 {
		w(" none.")
	}
	for _, k := range sortedKeys(m.ActGate) {
		w(" %s %d;", k, m.ActGate[k])
	}
	w("\n\n## (d) Red-team drills\n\n%s\n", r.Drills.Note)
	if r.Drills.N > 0 {
		w("Time to gate, hours: median %s, max %s.\n", g(r.Drills.TimeToGateHoursMedian), g(r.Drills.TimeToGateHoursMax))
	}
	return b.String()
}

func counts(m map[string]int) string {
	if len(m) == 0 {
		return "none"
	}
	var parts []string
	for _, k := range sortedKeys(m) {
		parts = append(parts, fmt.Sprintf("%s %d", k, m[k]))
	}
	return strings.Join(parts, ", ")
}

func dash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}

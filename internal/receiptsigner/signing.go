func LoadOrCreateSigningKey(path, domain string) (computerevent.SigningKey, error) {
	key, _, err := LoadOrCreateSigningKeyWithProvenance(path, domain)
	return key, err
}

// KeyProvenance is what the signer knows about its key's origin. A key the
// signer generates is recorded beside it (key.ed25519.provenance.json), so a
// key generated over a recorded prior key is never silent: the host pins a
// computer's verifier key, and a regenerated key locks the computer out of
// every later verifier checkpoint until the owner re-pins it
// (docs/problems/verifier-key-regenerated-locks-out-checkpoints-2026-11-02.md).
// The signer still generates: the autoputer requires the verifier signer
// unit, so refusing to start would brick the computer; the guest reports
// the change and the host's pin decides.
type KeyProvenance struct {
	KeyID string `json:"key_id"`
	// GeneratedAt is when this key was generated; zero for a key from
	// before the record existed.
	GeneratedAt time.Time `json:"generated_at,omitempty"`
	// Generated reports a key generated by this load (this boot).
	Generated bool `json:"-"`
	// PriorKeyID names the key the record held when this key was generated
	// over it ("unknown" when the record could not be read). Empty for a key
	// generated on a disk with no record: genesis, or a disk lost with it.
	PriorKeyID string `json:"prior_key_id,omitempty"`
}

func provenancePath(keyPath string) string { return keyPath + ".provenance.json" }

func readProvenance(keyPath string) (KeyProvenance, bool, error) {
	raw, err := os.ReadFile(provenancePath(keyPath))
	if errors.Is(err, os.ErrNotExist) {
		return KeyProvenance{}, false, nil
	}
	if err != nil {
		return KeyProvenance{}, true, err
	}
	var record KeyProvenance
	if err := json.Unmarshal(raw, &record); err != nil || record.KeyID == "" {
		return KeyProvenance{}, true, errProvenanceCorrupt
	}
	return record, true, nil
}

// errProvenanceCorrupt is a record that was read and does not decode: it is
// rewritten. Any other read error is transient and leaves the record alone.
var errProvenanceCorrupt = errors.New("receipt signer: unreadable key provenance")

// writeProvenance replaces the record through a temporary of its own
// (O_EXCL, unique name), synced before the rename.
func writeProvenance(keyPath string, record KeyProvenance) error {
	raw, err := json.Marshal(record)
	if err != nil {
		return err
	}
	file, err := os.CreateTemp(filepath.Dir(keyPath), filepath.Base(provenancePath(keyPath))+".tmp-*")
	if err != nil {
		return err
	}
	temporary := file.Name()
	if _, err = file.Write(raw); err == nil {
		err = file.Sync()
	}
	if closeErr := file.Close(); err == nil {
		err = closeErr
	}
	if err == nil {
		err = os.Rename(temporary, provenancePath(keyPath))
	}
	if err != nil {
		_ = os.Remove(temporary)
	}
	return err
}

// LoadOrCreateSigningKeyWithProvenance is LoadOrCreateSigningKey reporting
// the key's provenance. A record that cannot be read or written never stops
// the signer; it is logged.
func LoadOrCreateSigningKeyWithProvenance(path, domain string) (computerevent.SigningKey, KeyProvenance, error) {
	path = filepath.Clean(path)
	prior, priorFound, priorErr := readProvenance(path)
	key, generated, err := loadOrCreateSigningKey(path, domain)
	if err != nil {
		return computerevent.SigningKey{}, KeyProvenance{}, err
	}
	provenance := KeyProvenance{KeyID: key.KeyID}
	switch {
	case generated:
		provenance.Generated = true
		provenance.GeneratedAt = time.Now().UTC()
		if priorErr != nil {
			provenance.PriorKeyID = "unknown"
		} else if priorFound && prior.KeyID != key.KeyID {
			provenance.PriorKeyID = prior.KeyID
		}
		if provenance.PriorKeyID != "" {
			log.Printf("receipt signer: %s key file missing; generated %s over prior key %s; a pinned computer must be re-pinned by the owner", domain, key.KeyID, provenance.PriorKeyID)
		} else {
			log.Printf("receipt signer: %s key generated: %s (no prior key recorded on this disk)", domain, key.KeyID)
		}
	case priorErr == nil && priorFound && prior.KeyID == key.KeyID:
		provenance = prior
		provenance.Generated = false
	default:
		// A key from before the record existed, or a record that names
		// another key or cannot be read: the key file is the authority.
		if priorErr != nil || (priorFound && prior.KeyID != key.KeyID) {
			log.Printf("receipt signer: %s key provenance does not name the loaded key %s; rewritten", domain, key.KeyID)
		}
	}
	transient := priorErr != nil && !errors.Is(priorErr, errProvenanceCorrupt)
	if (provenance.Generated || !transient) && !(priorErr == nil && priorFound && prior == provenance) {
		if writeErr := writeProvenance(path, provenance); writeErr != nil {
			log.Printf("receipt signer: %s key provenance not recorded: %v", domain, writeErr)
		}
	}
	return key, provenance, nil
}

func loadOrCreateSigningKey(path, domain string) (computerevent.SigningKey, bool, error) {
	generatedKey := false
	path, domain = filepath.Clean(path), filepath.Clean(domain)
	if !filepath.IsAbs(path) || path == string(os.PathSeparator) || domain == "." || domain == string(os.PathSeparator) {
		return computerevent.SigningKey{}, false, fmt.Errorf("receipt signer: absolute key path and domain are required")
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return computerevent.SigningKey{}, false, err
	}
	privateKey, err := readSigningKey(path)
	if errors.Is(err, os.ErrNotExist) {
		_, generated, generateErr := ed25519.GenerateKey(rand.Reader)
		if generateErr != nil {
			return computerevent.SigningKey{}, false, generateErr
		}
		file, createErr := os.OpenFile(path, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0o600)
		if errors.Is(createErr, os.ErrExist) {
			privateKey, err = readSigningKey(path)
		} else if createErr != nil {
			return computerevent.SigningKey{}, false, createErr
		} else {
			if _, writeErr := file.Write(generated); writeErr != nil {
				file.Close()
				_ = os.Remove(path)
				return computerevent.SigningKey{}, false, writeErr
			}
			if syncErr := file.Sync(); syncErr != nil {
				file.Close()
				_ = os.Remove(path)
				return computerevent.SigningKey{}, false, syncErr
			}
			if closeErr := file.Close(); closeErr != nil {
				_ = os.Remove(path)
				return computerevent.SigningKey{}, false, closeErr
			}
			privateKey, err = generated, nil
			generatedKey = true
		}
	}
	if err != nil {
		return computerevent.SigningKey{}, false, err
	}
	publicKey := privateKey.Public().(ed25519.PublicKey)
	digest := sha256.Sum256(publicKey)
	return computerevent.SigningKey{SignerRef: computerevent.SignerRef{SignerDomain: domain, KeyID: domain + "-" + hex.EncodeToString(digest[:8])}, PrivateKey: privateKey}, generatedKey, nil
}

func readSigningKey(path string) (ed25519.PrivateKey, error) {
	info, err := os.Lstat(path)
	if err != nil {
		return nil, err
	}
	stat, ok := info.Sys().(*syscall.Stat_t)
	if !ok || int(stat.Uid) != os.Geteuid() {
		return nil, fmt.Errorf("receipt signer: existing key owner mismatch")
	}
	if !info.Mode().IsRegular() || info.Mode().Perm() != 0o600 {
		return nil, fmt.Errorf("receipt signer: existing key must be a regular mode-0600 file")
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	if len(raw) != ed25519.PrivateKeySize {
		return nil, fmt.Errorf("receipt signer: invalid private key size")
	}
	return ed25519.PrivateKey(raw), nil
}

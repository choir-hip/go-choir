#!/usr/bin/env python3
"""The app's TetraMark geometry, generated from the brand drawing.

Source of truth: frontend/src/lib/tetramark.ts (TETRA_MARK_VIEWBOX, TETRA_MARK_PATHS: three closed polygons, the three
blades). The block between the `tetramark-data` markers in mobile/AutoradioLab/mark.contract holds, per blade i:

  ax_i, ay_i          pole A: the brand polygon exactly, as (x - 256) / 256 (the mark is centred, radius about 1)
  bx_i, by_i, bz_i    pole B: the same number of points moved onto a sharp tetrahedron seen in perspective (below)
  bn_i                the unit normal of the blade's face in pole B (for shading)
  ru_i                the blade's radial direction (a unit vector from the mark's centre), the way it grows apart
  fx_i, fy_i, fz_i    the three corners of the blade's tetrahedron face in pole B (the translucent solid)

The brand mark is a triskelion: three chevrons chasing round a centre. Read as a tetrahedron seen from a vertex, each
chevron is the angle at one base corner P_i of one face: one arm along the outer edge to the next corner, one arm along the
inner edge to the apex Q. Pole B is that tetrahedron built for real (corners P_i taken from the brand's chevron apexes, the
apex Q toward the viewer a little off-centre, so the perspective is as hand-drawn as the brand), turned a little to show
depth, with each chevron rebuilt as a straight, sharp band inside its face. Each band polygon is resampled to the brand
polygon's own vertex count, shifted and oriented to the alignment that moves the points least, with the band's six corners
snapped to vertices, so every brand point has a partner and a blend of the poles is a smooth morph.

  gen-tetramark.py            rewrite the block in mark.contract
  gen-tetramark.py --check    exit 1 if the block differs from what the brand drawing gives (the drift test)
  gen-tetramark.py --launch-image PATH   also draw the flat mark as a PNG (needs ImageMagick), for the launch screen

Run with `python3 -I` (no repo directory on the import path)."""
import math
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TS = ROOT / "frontend/src/lib/tetramark.ts"
CONTRACT = ROOT / "mobile/AutoradioLab/mark.contract"
BEGIN = "  // BEGIN tetramark-data (generated by mobile/scripts/gen-tetramark.py from frontend/src/lib/tetramark.ts; do not edit)"
END = "  // END tetramark-data"

# Pole B's construction (brand box 512, then normalised). Base corners are the chevron apexes of blades 0, 1, 2; the next
# corner along each blade's outer arm is blade 0 -> corner 2, blade 1 -> corner 0, blade 2 -> corner 1.
CORNERS = [(272, 40), (44, 418), (468, 460)]
NEXT = [2, 0, 1]
APEX = (271, 309)
Z_BASE, Z_APEX = -0.2, 0.55
BAND = 0.125         # band width, in radii
ARM = 0.93           # how much of an edge an arm covers
VIEW_YAW, VIEW_PITCH = -0.3, 0.28   # how pole B is turned to show its depth


def brand_paths():
    src = TS.read_text()
    if "'0 0 512 512'" not in src:
        sys.exit("tetramark.ts: viewBox is no longer 0 0 512 512; update this script")
    body = src.split("TETRA_MARK_PATHS = [", 1)[1].split("];", 1)[0]
    paths = re.findall(r"'([^']+)'", body)
    blades = []
    for d in paths:
        pts = [(float(x), float(y)) for _, x, y in re.findall(r"([ML])\s*([-\d.]+)\s+([-\d.]+)", d)]
        if not d.strip().endswith("Z") or len(pts) < 3 or re.search(r"[^MLZ\d.\s-]", d):
            sys.exit("tetramark.ts: a blade is not a closed M/L polygon; update this script")
        blades.append(pts)
    if len(blades) != 3:
        sys.exit("tetramark.ts: expected three blades")
    return blades


def nm(p):
    return ((p[0] - 256) / 256, (p[1] - 256) / 256)


def sub(a, b): return tuple(x - y for x, y in zip(a, b))
def add(a, b): return tuple(x + y for x, y in zip(a, b))
def mul(a, k): return tuple(x * k for x in a)
def dot(a, b): return sum(x * y for x, y in zip(a, b))
def norm(a): return math.sqrt(dot(a, a))
def unit(a): return mul(a, 1 / norm(a))
def cross(a, b): return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def tetra():
    """The three face-corner triples and each blade's 3D band polygon (six corners), before the view turn."""
    px = [nm(c) + (Z_BASE,) for c in CORNERS]
    q = nm(APEX) + (Z_APEX,)
    bands = []
    faces = []
    for i in range(3):
        p, pn = px[i], px[NEXT[i]]
        e1, e2 = sub(pn, p), sub(q, p)
        u1 = unit(e1)
        perp = unit(sub(e2, mul(u1, dot(e2, u1))))
        l1, l2 = norm(e1) * ARM, norm(e2) * ARM
        c2 = (dot(e2, u1) / norm(e2), dot(e2, perp) / norm(e2))     # the inner arm's direction in the face basis
        phi = math.atan2(c2[1], c2[0])
        w = BAND
        t = w * (1 + math.cos(phi)) / math.sin(phi)
        d2 = (math.cos(phi), math.sin(phi))
        n2 = (math.sin(phi), -math.cos(phi))
        corner = (t * d2[0] + w * n2[0], t * d2[1] + w * n2[1])
        def lift(uv): return add(p, add(mul(u1, uv[0]), mul(perp, uv[1])))
        poly2 = [
            (0, 0),
            (l1, 0),
            (0.8 * l1, w),
            corner,
            (0.8 * l2 * d2[0] + w * n2[0], 0.8 * l2 * d2[1] + w * n2[1]),
            (l2 * d2[0], l2 * d2[1]),
        ]
        bands.append([lift(v) for v in poly2])
        faces.append((p, pn, q))
    return bands, faces


def perimeter(poly):
    """Cumulative arclength fractions of a closed polygon's vertices (the first is 0)."""
    acc = [0.0]
    for i in range(len(poly)):
        a, b = poly[i], poly[(i + 1) % len(poly)]
        acc.append(acc[-1] + math.dist(a, b))
    total = acc[-1]
    return [x / total for x in acc[:-1]], acc, total


def point_at(poly, f):
    _, acc, total = perimeter(poly)
    s = (f % 1.0) * total
    for i in range(len(poly)):
        if s <= acc[i + 1] + 1e-12:
            a, b = poly[i], poly[(i + 1) % len(poly)]
            seg = acc[i + 1] - acc[i]
            k = 0 if seg == 0 else (s - acc[i]) / seg
            return add(a, mul(sub(b, a), k))
    return poly[0]


def match(brand2, band3):
    """Resample band3 to len(brand2) points aligned to the brand polygon; the band's corners are kept as vertices."""
    n = len(brand2)
    fr, _, _ = perimeter([(x, y) for x, y in brand2])
    best = None
    for orient in (1, -1):
        band = band3 if orient == 1 else [band3[0]] + band3[:0:-1]
        for step in range(0, 400):
            s = step / 400
            pts = [point_at(band, f + s) for f in fr]
            cost = sum((pts[j][0] - brand2[j][0]) ** 2 + (pts[j][1] - brand2[j][1]) ** 2 for j in range(n))
            if best is None or cost < best[0]:
                best = (cost, band, s)
    _, band, s = best
    bfr, _, _ = perimeter(band)
    pts = [point_at(band, f + s) for f in fr]
    taken = set()
    for k, v in enumerate(band):
        f = (bfr[k] - s) % 1.0
        cand = sorted(range(n), key=lambda j: min(abs(fr[j] - f), 1 - abs(fr[j] - f)))
        for j in cand:
            if j not in taken:
                taken.add(j)
                pts[j] = v
                break
    return pts


def view(p):
    """Turn a B-pose point by the view (yaw about y, pitch about x)."""
    x, y, z = p
    sa, ca = math.sin(VIEW_YAW), math.cos(VIEW_YAW)
    x, z = x * ca + z * sa, z * ca - x * sa
    sb, cb = math.sin(VIEW_PITCH), math.cos(VIEW_PITCH)
    y, z = y * cb - z * sb, y * sb + z * cb
    return (x, y, z)


def model():
    brand = [[nm(p) for p in b] for b in brand_paths()]
    bands, faces = tetra()
    out = []
    for i in range(3):
        b3 = match(brand[i], bands[i])
        b3v = [view(p) for p in b3]
        f3 = [view(p) for p in faces[i]]
        nrm = unit(cross(sub(f3[1], f3[0]), sub(f3[2], f3[0])))
        if nrm[2] < 0:
            nrm = mul(nrm, -1)
        cx = sum(p[0] for p in brand[i]) / len(brand[i])
        cy = sum(p[1] for p in brand[i]) / len(brand[i])
        m = math.hypot(cx, cy)
        out.append(dict(a=brand[i], b=b3v, n=nrm, u=(cx / m, cy / m), f=f3))
    return out


def num(v):
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def block():
    out = [BEGIN]
    for i, m in enumerate(model()):
        lst = lambda vs: "[" + ", ".join(num(v) for v in vs) + "]"
        out.append(f"  derive ax{i} = {lst(p[0] for p in m['a'])}")
        out.append(f"  derive ay{i} = {lst(p[1] for p in m['a'])}")
        out.append(f"  derive bx{i} = {lst(p[0] for p in m['b'])}")
        out.append(f"  derive by{i} = {lst(p[1] for p in m['b'])}")
        out.append(f"  derive bz{i} = {lst(p[2] for p in m['b'])}")
        out.append(f"  derive bn{i} = {lst(m['n'])}")
        out.append(f"  derive ru{i} = {lst(m['u'])}")
        out.append(f"  derive fx{i} = {lst(p[0] for p in m['f'])}")
        out.append(f"  derive fy{i} = {lst(p[1] for p in m['f'])}")
        out.append(f"  derive fz{i} = {lst(p[2] for p in m['f'])}")
    out.append(END)
    return "\n".join(out)


def current(text):
    a = text.find(BEGIN)
    b = text.find(END)
    if a < 0 or b < 0:
        return None
    return text[a : b + len(END)]


def launch_image(path):
    cmd = ["magick", "-size", "512x512", "xc:none", "-fill", "#3b82f6"]
    for blade in brand_paths():
        cmd += ["-draw", "polygon " + " ".join(f"{x},{y}" for x, y in blade)]
    cmd += [path]
    subprocess.run(cmd, check=True)


def main():
    if __name__ != "__main__":
        return
    text = CONTRACT.read_text()
    want = block()
    if "--check" in sys.argv:
        if current(text) != want:
            print("DRIFT: mobile/AutoradioLab/mark.contract differs from frontend/src/lib/tetramark.ts; run: python3 -I mobile/scripts/gen-tetramark.py")
            sys.exit(1)
        print("tetramark data matches frontend/src/lib/tetramark.ts")
        return
    have = current(text)
    if have is None:
        sys.exit("markers missing in mark.contract")
    CONTRACT.write_text(text.replace(have, want))
    if "--launch-image" in sys.argv:
        launch_image(sys.argv[sys.argv.index("--launch-image") + 1])


main()

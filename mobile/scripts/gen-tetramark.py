#!/usr/bin/env python3
"""The app's TetraMark geometry, generated from the brand drawing.

Source of truth: frontend/src/lib/tetramark.ts (TETRA_MARK_VIEWBOX, TETRA_MARK_PATHS: three closed polygons, the three
blades). This script copies those points, as (x - 256) / 256 so the mark is centred on the origin with radius about 1,
into the block between the `tetramark-data` markers in mobile/AutoradioLab/mark.contract, and gives each point a depth
z from the blade's tetrahedron face plane: the three blades are the three visible faces of a tetrahedron seen from a
vertex, the vertex toward the viewer, each face sloping away along its own outward direction u:  z = C - S * (p . u).
The face normal (S*ux, S*uy, 1) / |.| is emitted too, for shading by facing.

  gen-tetramark.py            rewrite the block in mark.contract
  gen-tetramark.py --check    exit 1 if the block differs from what the brand drawing gives (the drift test)
  gen-tetramark.py --launch-image PATH   also draw the flat mark as a PNG (needs ImageMagick), for the launch screen

Run with `python3 -I` (no repo directory on the import path)."""
import math
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TS = ROOT / "frontend/src/lib/tetramark.ts"
CONTRACT = ROOT / "mobile/AutoradioLab/mark.contract"
BEGIN = "  // BEGIN tetramark-data (generated by mobile/scripts/gen-tetramark.py from frontend/src/lib/tetramark.ts; do not edit)"
END = "  // END tetramark-data"
C, S = 0.45, 0.8


def brand_paths():
    src = TS.read_text()
    if "'0 0 512 512'" not in src:
        sys.exit("tetramark.ts: viewBox is no longer 0 0 512 512; update this script")
    body = src.split("TETRA_MARK_PATHS = [", 1)[1].split("];", 1)[0]
    paths = re.findall(r"'([^']+)'", body)
    blades = []
    for d in paths:
        pts = []
        for cmd, x, y in re.findall(r"([ML])\s*([-\d.]+)\s+([-\d.]+)", d):
            pts.append((float(x), float(y)))
        if not d.strip().endswith("Z") or len(pts) < 3 or re.search(r"[^MLZ\d.\s-]", d):
            sys.exit("tetramark.ts: a blade is not a closed M/L polygon; update this script")
        blades.append(pts)
    if len(blades) != 3:
        sys.exit("tetramark.ts: expected three blades")
    return blades


def num(v):
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def block():
    out = [BEGIN]
    for i, pts in enumerate(brand_paths()):
        ps = [((x - 256) / 256, (y - 256) / 256) for x, y in pts]
        cx = sum(p[0] for p in ps) / len(ps)
        cy = sum(p[1] for p in ps) / len(ps)
        n = math.hypot(cx, cy)
        ux, uy = cx / n, cy / n
        zs = [C - S * (x * ux + y * uy) for x, y in ps]
        nl = math.sqrt(S * S + 1)
        out.append(f"  derive bx{i} = [{', '.join(num(x) for x, _ in ps)}]")
        out.append(f"  derive by{i} = [{', '.join(num(y) for _, y in ps)}]")
        out.append(f"  derive bz{i} = [{', '.join(num(z) for z in zs)}]")
        out.append(f"  derive bn{i} = [{num(S * ux / nl)}, {num(S * uy / nl)}, {num(1 / nl)}]")
    out.append(END)
    return "\n".join(out)


def current(text):
    a = text.find(BEGIN)
    b = text.find(END)
    if a < 0 or b < 0:
        return None
    return text[a : b + len(END)]


def launch_image(path):
    pts = brand_paths()
    cmd = ["magick", "-size", "512x512", "xc:none", "-fill", "#3b82f6"]
    for blade in pts:
        cmd += ["-draw", "polygon " + " ".join(f"{x},{y}" for x, y in blade)]
    cmd += [path]
    subprocess.run(cmd, check=True)


def main():
    text = CONTRACT.read_text()
    want = block()
    if "--check" in sys.argv:
        if current(text) != want:
            print("DRIFT: mobile/AutoradioLab/mark.contract differs from frontend/src/lib/tetramark.ts; run: python3 -I mobile/scripts/gen-tetramark.py")
            sys.exit(1)
        print("tetramark data matches frontend/src/lib/tetramark.ts")
        return
    have = current(text)
    if have is None:
        sys.exit("markers missing in mark.contract")
    CONTRACT.write_text(text.replace(have, want))
    if "--launch-image" in sys.argv:
        launch_image(sys.argv[sys.argv.index("--launch-image") + 1])


main()

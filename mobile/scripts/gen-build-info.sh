#!/bin/sh
# Writes mobile/AutoradioLab/build-info.gen.ts (gitignored): the git commit this app is built from, for the About page (about.ts).
# commit = full sha, or `unknown` with no git; dirty = tracked files differ from HEAD (untracked and ignored files do not count);
# committed = the commit's UTC date, "YYYY-MM-DD HH:MM". dirty is scoped to the mobile/ directory (git status of mobile/ only; a change
# elsewhere in the repo does not make the app dirty). Run by exact.sh (every Exact command, so every entry that builds a bundle:
# build-lab.sh, proof-real.sh, the build queue and device install), by sync-exact-package.sh, and by bunfig.toml before tests.
set -u
HERE="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$HERE/AutoradioLab/build-info.gen.ts"
# The file outlives a checkout of an older commit that has no .gitignore line for it, and would make that tree "dirty" (the build queue
# refuses a dirty tree). So it is also excluded in the repository's own info/exclude, which every checkout of every commit honours.
EXC="$(git -C "$HERE" rev-parse --path-format=absolute --git-path info/exclude 2>/dev/null || true)"
if [ -n "$EXC" ]; then mkdir -p "$(dirname "$EXC")"; grep -qxF '/mobile/AutoradioLab/build-info.gen.ts' "$EXC" 2>/dev/null || printf '/mobile/AutoradioLab/build-info.gen.ts\n' >> "$EXC"; fi
COMMIT=unknown; DIRTY=false; WHEN=""
if SHA="$(git -C "$HERE" rev-parse HEAD 2>/dev/null)" && [ -n "$SHA" ]; then
  COMMIT="$SHA"
  WHEN="$(TZ=UTC git -C "$HERE" log -1 --format=%cd --date=format-local:'%Y-%m-%d %H:%M' 2>/dev/null || true)"
  [ -z "$(git -C "$HERE" status --porcelain --untracked-files=no -- . 2>/dev/null | head -1)" ] || DIRTY=true
fi
NEW="// Generated by scripts/gen-build-info.sh. Do not edit; gitignored.
export const BUILD_INFO = { commit: '$COMMIT', dirty: $DIRTY, committed: '$WHEN' };"
[ -f "$OUT" ] && [ "$(cat "$OUT")" = "$NEW" ] || printf '%s\n' "$NEW" > "$OUT"

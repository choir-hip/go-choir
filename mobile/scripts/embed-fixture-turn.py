#!/usr/bin/env python3
"""Embed fixtures/turns/plain/mic.caf in the kit (FixtureTurn.swift) so the lab app has a kept turn to inject
through the live engine and to replay, on a simulator or a phone, with no files copied in. macOS: afconvert."""
import base64, os, subprocess, tempfile

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
src = os.path.join(ROOT, "fixtures", "turns", "plain")
with tempfile.TemporaryDirectory() as t:
    w = os.path.join(t, "m.wav")
    subprocess.check_call(["/usr/bin/afconvert", "-f", "WAVE", "-d", "LEI16@16000", "-c", "1", os.path.join(src, "mic.caf"), w])
    b64 = base64.b64encode(open(w, "rb").read()).decode()
ctx = open(os.path.join(src, "context.json")).read()
out = os.path.join(ROOT, "AutoradioKit", "Sources", "AutoradioKit", "FixtureTurn.swift")
with open(out, "w") as f:
    f.write('''// Generated by mobile/scripts/embed-fixture-turn.py from fixtures/turns/plain. A synthesised utterance (say), no third-party audio.
import Foundation

/// The bundled kept turn "fixture-plain": its audio and context, written into the store on first run.
public enum FixtureTurn {
    public static let name = "fixture-plain"
    static let base64 = "%s"
    static let context = #"""
%s
"""#
    /// The microphone audio as a WAV file in the temporary directory.
    static func materialise() -> URL? {
        guard let d = Data(base64Encoded: base64) else { return nil }
        let u = FileManager.default.temporaryDirectory.appendingPathComponent("autoradio-fixture-turn.wav")
        if !FileManager.default.fileExists(atPath: u.path) { try? d.write(to: u) }
        return u
    }
    /// Make the kept turn exist in `store` (mic.caf holds the WAV: AVAudioFile reads by content).
    public static func install(into store: KeptTurnStore) {
        let folder = store.root.appendingPathComponent(name)
        guard !FileManager.default.fileExists(atPath: folder.appendingPathComponent("mic.caf").path),
              let d = Data(base64Encoded: base64) else { return }
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        try? d.write(to: folder.appendingPathComponent("mic.caf"))
        try? Data(context.utf8).write(to: folder.appendingPathComponent("context.json"))
    }
}
''' % (b64, ctx.strip()))
print("embedded turn", len(b64), "bytes base64")

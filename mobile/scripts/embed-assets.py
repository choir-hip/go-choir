#!/usr/bin/env python3
"""Embeds mobile/themes/*.json and mobile/fixtures/demo/*.json into Swift, so the app carries them with no resource bundle
(Exact compiles Swift only). Writes AutoradioKit/Sources/AutoradioKit/BundledThemes.generated.swift and
DemoFixtures.generated.swift. Run by sync-exact-package.sh on every build; the outputs are tracked so `swift test` works."""
import glob, os, sys
HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(HERE, "AutoradioKit", "Sources", "AutoradioKit")

def emit(name, enum, var, pattern, doc):
    items = sorted(glob.glob(os.path.join(HERE, pattern)))
    lines = [f"// Generated by scripts/embed-assets.py from {pattern}. Do not edit.", "import Foundation", "",
             f"public enum {enum} {{", f"    /// {doc}", f"    public static let {var}: [String: String] = ["]
    for p in items:
        key = os.path.splitext(os.path.basename(p))[0]
        body = open(p).read()
        lines.append(f'        "{key}": #"""\n{body.rstrip()}\n"""#,')
    lines += ["    ]", "}", ""]
    new = "\n".join(lines)
    path = os.path.join(OUT, name)
    if not os.path.exists(path) or open(path).read() != new:
        open(path, "w").write(new)
    print(name, len(items), "files")

emit("BundledThemes.generated.swift", "BundledThemes", "json", "themes/*.json", "Theme id -> schema v3 JSON text.")
emit("DemoFixtures.generated.swift", "DemoFixtureData", "files", "fixtures/demo/*.json", "File name (no extension) -> JSON text.")
